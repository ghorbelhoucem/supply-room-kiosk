def run():
    db = SessionLocal()
    try:
        created = 0
        updated = 0
        for op_id, password, name in OPERATOR_DATA:
            display_name = name if name else f"Operator-{op_id}"
            user = db.query(User).filter(
                User.operator_id == op_id,
                User.auth_kind == AuthKind.operator,
            ).one_or_none()

            if user is None:
                db.add(User(
                    name=display_name,
                    role=UserRole.supervisor,  # fallback label only, not enforced
                    auth_kind=AuthKind.operator,
                    operator_id=op_id,
                    password_hash=hash_secret(password),
                ))
                created += 1
            else:
                user.name = display_name
                user.password_hash = hash_secret(password)
                updated += 1

        db.commit()
        print(f"Done. Created {created} new operator(s), updated {updated} existing.")
        print(f"Total operators in seed list: {len(OPERATOR_DATA)}")
    finally:
        db.close()


if __name__ == "__main__":
    run()
